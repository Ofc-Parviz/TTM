
namespace TeamTaskManagement.Domain.Enums {
    /// <summary>
    /// وضعیت وظیفه محول شده به عضو تیم
    /// </summary>
    public enum TeamTaskStatus {

        /// <summary>
        /// در صف انتظار برای رسیدگی - برای زمانی که وظیفه
        /// تعریف شده و در انتظار واکنش از طرف کاربر مسئول است
        /// </summary>
        Pending = 0,

        /// <summary>
        /// در حال انجام - زمانی که کاربر مسئول به سیستم اعلام کند که
        /// کار محول شده را شروع کرده است، وضعیت روی این تنظیم میشود
        /// </summary>
        OnGoing = 1,

        /// <summary>
        /// اعلام شده بعنوان تکمیل - زمانی که کاربر مسئول به سیستم
        /// اعلام کند که وظیفه محول شده را با موفقیت انجام داده، وضعیت روی این تنظیم میشود
        /// </summary>
        ClaimedAsComplete = 2,

        /// <summary>
        /// اعلام شده بعنوان شکست - زمانی که کاربر مسئول به سیستم
        /// اعلام کند که در انجام وظیفه محول شده شکست خورده، وضعیت روی این تنظیم میشود
        /// </summary>
        ClaimedAsFailure = 3,

        /// <summary>
        /// فرمان داده شده برای تلاش مجدد - زمانی که کاربر مسئول یکی از حالت
        /// های موفقیت یا شگست را اعلام کرده باشد و کاربر محول کننده در واکنش
        /// خود پس از بررسی شرایط، دستور به تلاش مجدد صادر کند، وضعیت روی این تنظیم میشود
        /// </summary>
        OrderedToTryAgain = 4,

        /// <summary>
        /// موافقت شده برای تلاش مجدد - زمانی که کاربر مسئول با دستور محول کننده
        /// مبنی بر تلاش مجدد موافقت و دوباره شروع کند، وضعیت روی این تنظیم میشود
        /// </summary>
        AcceptedToTryAgain = 5,

        /// <summary>
        /// مخالفت شده برای تلاش مجدد - زمانی که کاربر مسئول با دستور محول
        /// کننده مبنی بر تلاش مجدد مخالفت کند، وضعیت روی این تنظیم میشود
        /// </summary>
        RejectedToTryAgain = 6,

        /// <summary>
        /// پایان یافته بعنوان شکست خورده - زمانی که کاربر محول کننده به این
        /// نتیجه برسد که کاربر مسئول در انجام وظیفه شکست خورده، و این موضوع را
        /// به سیستم اعلام کند، وضعیت روی این تنظیم شده و پرونده وظیفه بسته خواهد شد
        /// </summary>
        ClosedAsFailure = 7,

        /// <summary>
        /// پایان یافته بعنوان شکست در ددلاین - زمانی که تاریخ ددلاین فرا برسد
        /// و وضعیت از «در صف انتظار» و «در حال انجام» جلوتر نرفته باشد،
        /// سیستم بطور خودکار وضعیت را روی این تنظیم خواهد کرد
        /// </summary>
        ClosedAsDeadlineFailure = 8,

        /// <summary>
        /// پایان یافته بعنوان تکمیل شده - زمانی که کاربر محول کننده به این
        /// نتیجه برسد که کاربر مسئول در انجام وظیفه موفق بوده، و این موضوع را
        /// به سیستم اعلام کند، وضعیت روی این تنظیم شده و پرونده وظیفه بسته خواهد شد
        /// </summary>
        ClosedAsComplete = 9
    }
}
